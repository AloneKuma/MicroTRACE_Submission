#!/usr/bin/env bash
# Create (or reuse) the GRE test cluster microtrace-gre on the dev host:
# kind with Calico (NetworkPolicy enforced) and an API-server audit policy,
# then the GRE identities, RBAC, admission policies and test workloads from
# src/k8s/gre/. Needs: source $MT_DEV/env.sh; kind and kubectl on PATH or in
# ~/microtrace-cluster/bin.
#
# Host rules (experiments/cluster/TEST-PLAN.md): record the baseline, pinned
# images and checksums only, touch nothing but this cluster, never prune.
# Kubeconfigs, the executor token and raw audit logs stay under
# $MT_DEV/gre-kind, outside the repository. gre-kind-down.sh deletes only
# this cluster.
set -euo pipefail

: "${MT_DEV:?source env.sh first}"
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
K8S="$REPO/src/k8s/gre"
BASE="$MT_DEV/gre-kind"
CLUSTER=microtrace-gre
CALICO_VERSION=v3.30.3
CALICO_SHA256=9382d2b27a76f40c170454b408653e6d71e2205ef0aef069e942bb690e7381d0
CALICO_IMAGES="docker.io/calico/cni:$CALICO_VERSION docker.io/calico/node:$CALICO_VERSION docker.io/calico/kube-controllers:$CALICO_VERSION"
PATH="$HOME/microtrace-cluster/bin:$PATH"
mkdir -p "$BASE"
chmod 700 "$BASE"
umask 077
ADMIN="$BASE/admin.kubeconfig"
LOG="$BASE/up.log"
exec > >(tee -a "$LOG") 2>&1

echo "== gre-kind-up $(date -u +%Y-%m-%dT%H:%M:%SZ)"
kind version
kubectl version --client | sed -n 1p   # sed reads it all: head -1 can SIGPIPE kubectl under pipefail
echo "PRE_ACTIVE_CONTAINERS=$(docker ps -q | wc -l)"
echo "KIND_CLUSTERS=$(kind get clusters 2>/dev/null | tr '\n' ' ')"

if kind get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
  echo "cluster $CLUSTER exists; re-applying manifests"
else
  # Remember whether the docker network "kind" existed, so down removes it
  # only if this script created it.
  if docker network inspect kind > /dev/null 2>&1; then
    echo existed > "$BASE/kind-network"
  else
    echo created > "$BASE/kind-network"
  fi
  calico="$BASE/calico-$CALICO_VERSION.yaml"
  if [ ! -f "$calico" ]; then
    curl -fsSL --max-time 120 -o "$calico" \
      "https://raw.githubusercontent.com/projectcalico/calico/$CALICO_VERSION/manifests/calico.yaml"
  fi
  echo "$CALICO_SHA256  $calico" | sha256sum -c -
  sed "s|__AUDIT_POLICY__|$K8S/audit-policy.yaml|" "$K8S/kind-config.yaml" > "$BASE/kind-config.yaml"
  kind create cluster --name "$CLUSTER" --config "$BASE/kind-config.yaml" --kubeconfig "$ADMIN" --wait 0s
  # Pull Calico once on the host and load it into the nodes, instead of
  # every node pulling from Docker Hub.
  for img in $CALICO_IMAGES; do
    docker image inspect "$img" > /dev/null 2>&1 || docker pull -q "$img"
    # kind load imports with --all-platforms, which fails when Docker keeps only this
    # platform's layers of a multi-arch image (containerd image store, found 2026-11-16 on
    # AWS); import the same saved image into each node without that flag instead.
    for node in $(kind get nodes --name "$CLUSTER"); do
      docker save "$img" | docker exec --privileged -i "$node" \
        ctr --namespace=k8s.io images import --digests --snapshotter=overlayfs - > /dev/null
    done
  done
  kubectl --kubeconfig "$ADMIN" apply -f "$calico" > /dev/null
fi

export KUBECONFIG="$ADMIN"
kubectl wait --for=condition=Ready nodes --all --timeout=300s
kubectl apply -f "$K8S/shop.yaml"
kubectl apply -f "$K8S/response-rbac.yaml"
kubectl apply -f "$K8S/response-policies.yaml"
kubectl -n shop rollout status deployment/checkout --timeout=180s
kubectl -n shop rollout status statefulset/ledger --timeout=180s

# The executor's own credential: a 24 h token for gre-executor, which may
# only mint tokens for the four response ServiceAccounts.
server="$(kubectl config view --raw -o jsonpath='{.clusters[0].cluster.server}')"
ca="$(kubectl config view --raw -o jsonpath='{.clusters[0].cluster.certificate-authority-data}')"
token="$(kubectl -n microtrace create token gre-executor --duration=24h)"
cat > "$BASE/executor.kubeconfig" <<EOF
apiVersion: v1
kind: Config
clusters:
  - name: $CLUSTER
    cluster: {server: "$server", certificate-authority-data: "$ca"}
users:
  - name: gre-executor
    user: {token: "$token"}
contexts:
  - name: gre-executor
    context: {cluster: $CLUSTER, user: gre-executor}
current-context: gre-executor
EOF
cat > "$BASE/gre.env" <<EOF
# GRE test cluster (generated by gre-kind-up.sh; never commit).
export MT_GRE_CLUSTER=$CLUSTER
export MT_GRE_KUBECONFIG=$BASE/executor.kubeconfig
export MT_GRE_ADMIN_KUBECONFIG=$ADMIN
export MT_KUBECTL=$(command -v kubectl)
EOF
echo "POST_ACTIVE_CONTAINERS=$(docker ps -q | wc -l)"
echo "cluster $CLUSTER ready; source $BASE/gre.env"
