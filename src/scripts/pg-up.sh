#!/usr/bin/env bash
# Start the TGS Postgres for development, bound to 127.0.0.1 only.
# Data, log and passwords live under $MT_DEV. Needs: source $MT_DEV/env.sh
#
# First run: initdb (scram-sha-256 passwords), database "tgs", and roles
#   tgs_admin   superuser for setup only
#   tgs_ingest  owns the TGS tables; the only writer (mtcore.tgs.run)
#   tgs_reader  SELECT only (Exp. 5 interfaces and the GRE)
#   tgs_hyp     inserts hypotheses only (6c; added to existing installs too)
#   gre_exec    owns schema gre: GRE nonces and attempts (7.1; added too)
# Passwords are generated into $MT_DEV/pg.env (outside the repository), with
# MT_TGS_DSN (ingest) and MT_TGS_TEST_DSN (tests). Source it to use them.
set -euo pipefail

: "${MT_DEV:?source env.sh first}"
DATA="$MT_DEV/pg-data"
PORT="${MT_PG_PORT:-55432}"
ENVF="$MT_DEV/pg.env"
LOG="$MT_DEV/logs/postgres.log"

running=0
pg_ctl -D "$DATA" status > /dev/null 2>&1 && running=1

new=0
if [ "$running" = 0 ] && [ ! -f "$DATA/PG_VERSION" ]; then
  new=1
  umask 077
  pw() { head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n'; }
  ADMIN_PW="$(pw)" INGEST_PW="$(pw)" READER_PW="$(pw)"
  printf '%s\n' "$ADMIN_PW" > "$MT_DEV/pg-admin.pw"
  initdb -D "$DATA" -U tgs_admin --pwfile="$MT_DEV/pg-admin.pw" --auth=scram-sha-256 -E UTF8 > /dev/null
  rm -f "$MT_DEV/pg-admin.pw"
  cat >> "$DATA/postgresql.conf" <<EOF
listen_addresses = '127.0.0.1'
port = $PORT
unix_socket_directories = '$DATA'
EOF
  cat > "$ENVF" <<EOF
# TGS Postgres credentials (generated by pg-up.sh; never commit).
export PGHOST=127.0.0.1 PGPORT=$PORT
export MT_PG_ADMIN_PASSWORD=$ADMIN_PW
export MT_TGS_DSN="host=127.0.0.1 port=$PORT dbname=tgs user=tgs_ingest password=$INGEST_PW"
export MT_TGS_READER_DSN="host=127.0.0.1 port=$PORT dbname=tgs user=tgs_reader password=$READER_PW"
export MT_TGS_TEST_DSN="\$MT_TGS_DSN"
EOF
fi

if [ "$running" = 1 ]; then
  echo "postgres already running on 127.0.0.1:$PORT"
else
  pg_ctl -D "$DATA" -l "$LOG" -w start > /dev/null
  echo "postgres up on 127.0.0.1:$PORT"
fi

if [ "$new" = 1 ]; then
  export PGPASSWORD="$ADMIN_PW"
  psql -h 127.0.0.1 -p "$PORT" -U tgs_admin -d postgres -v ON_ERROR_STOP=1 -q <<EOF
CREATE ROLE tgs_ingest LOGIN PASSWORD '$INGEST_PW';
CREATE ROLE tgs_reader LOGIN PASSWORD '$READER_PW';
CREATE DATABASE tgs OWNER tgs_ingest;
EOF
  psql -h 127.0.0.1 -p "$PORT" -U tgs_admin -d tgs -v ON_ERROR_STOP=1 -q <<EOF
REVOKE ALL ON DATABASE tgs FROM PUBLIC;
GRANT CONNECT ON DATABASE tgs TO tgs_ingest, tgs_reader;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO tgs_ingest;
GRANT USAGE ON SCHEMA public TO tgs_reader;
ALTER DEFAULT PRIVILEGES FOR ROLE tgs_ingest IN SCHEMA public GRANT SELECT ON TABLES TO tgs_reader;
EOF
  unset PGPASSWORD
  echo "created database tgs and roles tgs_ingest, tgs_reader; credentials in $ENVF"
fi

# tgs_hyp (6c): the hypothesis generator; added to existing installs too. It
# may insert hypotheses and read; the grants are made by the TGS schema.
if ! grep -q MT_TGS_HYP_DSN "$ENVF"; then
  # shellcheck disable=SC1090
  . "$ENVF"
  HYP_PW="$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  PGPASSWORD="$MT_PG_ADMIN_PASSWORD" psql -h 127.0.0.1 -p "$PORT" -U tgs_admin -d tgs -v ON_ERROR_STOP=1 -q <<EOF
CREATE ROLE tgs_hyp LOGIN PASSWORD '$HYP_PW';
GRANT CONNECT ON DATABASE tgs TO tgs_hyp;
GRANT USAGE ON SCHEMA public TO tgs_hyp;
EOF
  echo "export MT_TGS_HYP_DSN=\"host=127.0.0.1 port=$PORT dbname=tgs user=tgs_hyp password=$HYP_PW\"" >> "$ENVF"
  echo "created role tgs_hyp (hypothesis generator)"
fi

# gre_exec (7.1): the GRE's nonce store and attempt records, in its own
# schema gre; added to existing installs too. It reads the TGS only through
# tgs_reader (MT_TGS_READER_DSN), on a separate connection.
if ! grep -q MT_GRE_DSN "$ENVF"; then
  # shellcheck disable=SC1090
  . "$ENVF"
  GRE_PW="$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  PGPASSWORD="$MT_PG_ADMIN_PASSWORD" psql -h 127.0.0.1 -p "$PORT" -U tgs_admin -d tgs -v ON_ERROR_STOP=1 -q <<EOF
CREATE ROLE gre_exec LOGIN PASSWORD '$GRE_PW';
GRANT CONNECT ON DATABASE tgs TO gre_exec;
CREATE SCHEMA gre AUTHORIZATION gre_exec;
ALTER ROLE gre_exec SET search_path = gre;
EOF
  echo "export MT_GRE_DSN=\"host=127.0.0.1 port=$PORT dbname=tgs user=gre_exec password=$GRE_PW\"" >> "$ENVF"
  echo "created role gre_exec and schema gre (GRE nonce store and attempts)"
fi
