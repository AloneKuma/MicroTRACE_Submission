#!/usr/bin/env bash
# B3 confirmation arm (RULE-confirmB3.md, user-confirmed 2026-11-10). Starts after VETO_DONE.
# Code ~/microtrace-ml/code3 (CODE3_COMMIT). STATUS lines prefixed CONFIRM; ends CONFIRM_DONE.
set -uo pipefail
W=$HOME/microtrace-ml; S=$W/STATUS; CODE=$W/code3
D=$HOME/microtrace-pilot-multistep/pilot-multistep
SW=${SW:-5}; C=qmax_confirmB3
st() { echo "$(date -u +%FT%TZ) CONFIRM $*" | tee -a "$S"; }
until grep -qE "Z VETO (VETO_DONE|STOP)" $S; do sleep 120; done
grep -qE "Z VETO STOP" $S && { st "not started (veto job stopped)"; exit 1; }
. "$HOME/microtrace-pilot-multistep/code/.venv/bin/activate"
export PYTHONPATH=$CODE/src/python PYTHONDONTWRITEBYTECODE=1 PYTHONHASHSEED=1
cd "$CODE" || exit 1
st "START code $(cat $W/CODE3_COMMIT) rule $(sha256sum $W/RULE-confirmB3.md | cut -c1-12)"
for F in A B; do
  python - "$W/cfg/fold$F-qmax_g0.001.yaml" "$W/models/fold$F-max/train.json" "$W/cfg/fold$F-$C.yaml" "$F" <<'EOF' \
    || { st "STOP config $F"; exit 1; }
import json, sys, yaml
src, tr, out, fold = sys.argv[1:]
d = yaml.safe_load(open(src, encoding="utf-8"))
g = json.load(open(tr, encoding="utf-8"))["gamma"]["0.001"]["B3"]
if g is None:
    raise SystemExit("gamma B3 0.001 missing")
d["ml"]["or_path"] = False
d["ml"]["veto"] = {"B3": g}
d["parameter_set_version"] = f"PILOT-CV-fold{fold}-qmax_confirmB3"
d.setdefault("fit", {})["confirm"] = "B3 at gamma 0.001"
with open(out, "w", encoding="utf-8") as fh:
    fh.write("# Generated by experiments/ml-crossfit/confirm.sh (B3 confirmation at gamma 0.001).\n")
    yaml.safe_dump(d, fh, sort_keys=False, allow_unicode=True, width=120)
print(g)
EOF
done
st "cuts B3 A $(grep -A1 'veto:' $W/cfg/foldA-$C.yaml | tail -1) B $(grep -A1 'veto:' $W/cfg/foldB-$C.yaml | tail -1)"
mkdir -p $W/cv-veto
if [ ! -f $W/cv-veto/$C/DONE ]; then
  for F in A B; do
    python src/scripts/pilot/score_pilot.py --pilot $D --split $W/test$F.json --half fit --params $W/cfg/fold$F-$C.yaml \
        --out-dir $W/cv-veto/$C --workers $SW > $W/cv-veto/$C.fold$F.log 2>&1 || st "$C fold$F score exit $?"
  done
  st "$C $(python src/scripts/pilot/crossfit_ml.py summarize --pilot $D --out-dir $W/cv-veto/$C --runs $W/folds.json:all)"
  for R in $W/cv-veto/$C/runs/*/; do
    [ -f $R/output.jsonl.gz ] || continue
    zcat $R/output.jsonl.gz | python -c '
import json, sys
keep = ("findingId", "findingType", "anomalyScore", "detectionPath", "mlStatus", "modelVersion")
out = [{k: o["record"].get(k) for k in keep} for o in map(json.loads, sys.stdin) if o["topic"] == "findings.v0"]
json.dump(out, open(sys.argv[1], "w"))' $R/findings.json && rm -f $R/output.jsonl.gz
  done
  touch $W/cv-veto/$C/DONE
fi
st "select $(python $W/confirm_select.py $W)"
st "CONFIRM_DONE disk $(df -h ~ | awk 'END{print $4}') free"
