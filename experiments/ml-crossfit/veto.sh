#!/usr/bin/env bash
# ML veto test (RULE-veto.md, user-confirmed 2026-11-10). Code in ~/microtrace-ml/code3 (CODE3_COMMIT).
# STATUS lines are prefixed VETO; ends VETO_DONE.
set -uo pipefail
W=$HOME/microtrace-ml; S=$W/STATUS; CODE=$W/code3
D=$HOME/microtrace-pilot-multistep/pilot-multistep
SW=${SW:-5}
st() { echo "$(date -u +%FT%TZ) VETO $*" | tee -a "$S"; }
. "$HOME/microtrace-pilot-multistep/code/.venv/bin/activate"
export PYTHONPATH=$CODE/src/python PYTHONDONTWRITEBYTECODE=1 PYTHONHASHSEED=1
cd "$CODE" || exit 1
X() { python src/scripts/pilot/crossfit_ml.py "$@"; }
other() { [ "$1" = A ] && echo B || echo A; }
st "START code $(cat $W/CODE3_COMMIT) rule $(sha256sum $W/RULE-veto.md | cut -c1-12)"
for F in A B; do
  T=$(other $F); M=$W/models/fold$F-max-veto
  [ -f $M/train.json ] || X train --pilot $D --params $W/params/fold$F-qmax.yaml --rows-dir $W/rows/fold$F-max \
      --runs $W/folds.json:$T --out-dir $M --alphas 0.5,0.25,0.1 > $M.log 2>&1 || { st "STOP train $F"; exit 1; }
  for a in B G H; do
    cmp -s $M/IF_$a.json $W/models/fold$F-max/IF_$a.json || { st "STOP fold$F IF_$a differs from fold$F-max"; exit 1; }
  done
  for AV in 0.5 0.25 0.1; do
    python - "$W/cfg/fold$F-qmax_g0.001.yaml" "$M/train.json" "$AV" "$W/cfg/fold$F-qmax_veto$AV.yaml" "$F" <<'EOF' \
      || { st "STOP config $F $AV"; exit 1; }
import json, sys, yaml
src, tr, av, out, fold = sys.argv[1:]
d = yaml.safe_load(open(src, encoding="utf-8"))
g = json.load(open(tr, encoding="utf-8"))["gamma"][av]
cut = {t: g[t] for t in ("B3", "H1")}
if any(v is None for v in cut.values()):
    raise SystemExit(f"alpha_v {av} not feasible: {cut}")
d["ml"]["or_path"] = False
d["ml"]["veto"] = cut
d["parameter_set_version"] = f"PILOT-CV-fold{fold}-qmax_veto{av}"
d.setdefault("fit", {})["alpha_veto"] = float(av)
with open(out, "w", encoding="utf-8") as fh:
    fh.write(f"# Generated by experiments/ml-crossfit/veto.sh (alpha_veto {av}).\n")
    yaml.safe_dump(d, fh, sort_keys=False, allow_unicode=True, width=120)
print(json.dumps(cut))
EOF
  done
  st "fold$F cuts $(python -c "import json;g=json.load(open('$M/train.json'))['gamma'];print(json.dumps({a:{t:g[a][t] for t in ('B3','H1')} for a in g}))")"
done
mkdir -p $W/cv-veto
for C in qmax_veto0.5 qmax_veto0.25 qmax_veto0.1; do
  [ -f $W/cv-veto/$C/DONE ] && continue
  for F in A B; do
    python src/scripts/pilot/score_pilot.py --pilot $D --split $W/test$F.json --half fit --params $W/cfg/fold$F-$C.yaml \
        --out-dir $W/cv-veto/$C --workers $SW > $W/cv-veto/$C.fold$F.log 2>&1 || st "$C fold$F score exit $?"
  done
  st "$C $(X summarize --pilot $D --out-dir $W/cv-veto/$C --runs $W/folds.json:all)"
  rm -f $W/cv-veto/$C/runs/*/output.jsonl.gz; touch $W/cv-veto/$C/DONE
done
st "select $(python $W/veto_select.py $W)"
st "VETO_DONE disk $(df -h ~ | awk 'END{print $4}') free"
